const fs=require('fs');
const p='server.js';
let s=fs.readFileSync(p,'utf8');
const start=s.indexOf('function cleanJson');
const end=s.indexOf('async function aiProduct',start);
if(start<0||end<0) throw new Error('cleanJson/aiProduct markers not found');
const clean="function cleanJson(t){let x=String(t||'').trim().replace(/^```(?:json)?\\s*/i,'').replace(/\\s*```$/i,'').trim();const a=x.indexOf('{'),b=x.lastIndexOf('}');if(a>=0&&b>a)x=x.slice(a,b+1);return JSON.parse(x);}\n";
s=s.slice(0,start)+clean+s.slice(end);
s=s.replaceAll('max_output_tokens:1800','max_output_tokens:3000,text:{format:{type:"json_object"}}');
fs.writeFileSync(p,s);
console.log('AI JSON resilience installed');
